    def test_hook_paths_work_from_arbitrary_cwd(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            dist = _dist(root)
            src = dist / "src" / "nexus_harness"
            # Real dispatch is required for a successful import path.
            import shutil

            shutil.rmtree(src)
            shutil.copytree(REPO / "src" / "nexus_harness", src)
            home = root / "claude-home"
            _write(home / "settings.json", '{"hooks": {}}\n', 0o600)
            _write(home / "CLAUDE.md", "# org\n", 0o644)
            engine = root / "engine"
            apply_live_install(
                plan_live_install(
                    "claude",
                    home=home,
                    dist=dist,
                    engine_root=engine,
                    backup_root=root / "backups",
                )
            )
            hook = engine / "hooks" / "claude_event.py"
            elsewhere = root / "elsewhere"
            elsewhere.mkdir()
            completed = subprocess.run(
                [sys.executable, str(hook), "--event", "SessionStart"],
                cwd=elsewhere,
                input="{}",
                text=True,
                capture_output=True,
            )
            self.assertEqual(completed.returncode, 0, completed.stderr)
            loaded = json.loads((home / "settings.json").read_text(encoding="utf-8"))
            commands = [
                hook["command"]
                for matchers in loaded["hooks"].values()
                for matcher in matchers
                for hook in matcher["hooks"]
                if "claude_event.py" in hook["command"]
            ]
            self.assertTrue(commands)
            for command in commands:
                self.assertIn(str(engine.resolve()), command)
                self.assertFalse(command.startswith("python3 hooks/claude_event.py"))

