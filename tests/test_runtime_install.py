    def test_claude_unrelated_hooks_and_settings_preserved(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            dist = _dist(root)
            home = root / "claude-home"
            settings = {
                "model": "opus",
                "permissions": {"deny": ["Bash(rm *)"]},
                "env": {"TOKEN": "must-not-drop"},
                "hooks": {
                    "PreToolUse": [
                        {
                            "hooks": [
                                {
                                    "type": "command",
                                    "command": "/tmp/keep-firewall.sh",
                                }
                            ]
                        }
                    ],
                    "SessionStart": [
                        {
                            "hooks": [
                                {
                                    "type": "command",
                                    "command": "/tmp/keep-session.sh",
                                }
                            ]
                        }
                    ],
                },
            }
            _write(home / "settings.json", json.dumps(settings, indent=2) + "\n", 0o600)
            _write(home / "CLAUDE.md", "# org rules\nkeep outside\n", 0o644)
            apply_live_install(
                plan_live_install(
                    "claude",
                    home=home,
                    dist=dist,
                    engine_root=root / "engine",
                    backup_root=root / "backups",
                )
            )
            loaded = json.loads((home / "settings.json").read_text(encoding="utf-8"))
            self.assertEqual(loaded["model"], "opus")
            self.assertEqual(loaded["permissions"], {"deny": ["Bash(rm *)"]})
            self.assertEqual(loaded["env"]["TOKEN"], "must-not-drop")
            pretool = loaded["hooks"]["PreToolUse"]
            cmds = [hook["command"] for matcher in pretool for hook in matcher["hooks"]]
            self.assertIn("/tmp/keep-firewall.sh", cmds)
            self.assertEqual(sum(1 for cmd in cmds if "claude_event.py" in cmd), 1)
            self.assertTrue(any(str(root / "engine") in cmd for cmd in cmds))
            claude_md = (home / "CLAUDE.md").read_text(encoding="utf-8")
            self.assertTrue(claude_md.startswith("# org rules\nkeep outside\n"))
            self.assertIn("NEXUS_HARNESS_BEGIN", claude_md)
            self.assertEqual(
                stat.S_IMODE((home / "settings.json").stat().st_mode), 0o600
            )

