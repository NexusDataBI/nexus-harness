REPO = Path(__file__).resolve().parents[1]


def _write(path: Path, text: str, mode: int = 0o644) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    os.chmod(path, mode)


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _dist(root: Path) -> Path:
    dist = root / "dist"
    (dist / "codex").mkdir(parents=True)
    (dist / "claude").mkdir(parents=True)
    (dist / "cursor").mkdir(parents=True)
    (dist / ".cursor" / "rules").mkdir(parents=True)
    (dist / "hooks").mkdir(parents=True)
    (dist / "src" / "nexus_harness").mkdir(parents=True)
    (dist / "core").mkdir(parents=True)
    _write(
        dist / "AGENTS.md",
        "<!-- GENERATED BY NEXUS HARNESS — DO NOT EDIT -->\n"
        "NEXUS WORKFLOW IS MANDATORY.\n",
    )
    _write(
        dist / "codex" / "config.toml",
        "# GENERATED BY NEXUS HARNESS — DO NOT EDIT\n"
        'sandbox_mode = "workspace-write"\n'
        'approval_policy = "on-request"\n',
    )
    _write(
        dist / "USER_RULES.md",
        "<!-- GENERATED BY NEXUS HARNESS — DO NOT EDIT -->\n"
        "NEXUS WORKFLOW IS MANDATORY.\n",
    )
    _write(
        dist / ".cursor" / "rules" / "nexus-workflow.mdc",
        "<!-- GENERATED BY NEXUS HARNESS — DO NOT EDIT -->\n"
        "NEXUS WORKFLOW IS MANDATORY.\n",
    )
    _write(
        dist / "cursor" / "sandbox.json",
        json.dumps(
            {
                "_generated_by": "GENERATED BY NEXUS HARNESS — DO NOT EDIT",
                "type": "workspace_readwrite",
            }
        )
        + "\n",
    )
    _write(
        dist / "claude" / "CLAUDE.md",
        "<!-- GENERATED BY NEXUS HARNESS — DO NOT EDIT -->\n"
        "NEXUS WORKFLOW IS MANDATORY.\n",
    )
    _write(
        dist / "claude" / "settings.json",
        json.dumps(
            {
                "hooks": {
                    "SessionStart": [
                        {
                            "hooks": [
                                {
                                    "type": "command",
                                    "command": "python3 hooks/claude_event.py --event SessionStart",
                                }
                            ]
                        }
                    ],
                    "PreToolUse": [
                        {
                            "hooks": [
                                {
                                    "type": "command",
                                    "command": "python3 hooks/claude_event.py --event PreToolUse",
                                }
                            ]
                        }
                    ],
                    "TaskCompleted": [
                        {
                            "hooks": [
                                {
                                    "type": "command",
                                    "command": (
                                        "python3 hooks/claude_event.py "
                                        "--event TaskCompleted --completion-gate"
                                    ),
                                }
                            ]
                        }
                    ],
                }
            }
        )
        + "\n",
    )
    _write(dist / "hooks" / "nexus_event.py", NEXUS_EVENT_WRAPPER)
    _write(dist / "hooks" / "claude_event.py", _HOOK_WRAPPER)
    _write(dist / "src" / "nexus_harness" / "__init__.py", "")
    _write(dist / "core" / "constitution.md", "NEXUS WORKFLOW IS MANDATORY.\n")
    return dist


def _ops(plan, destination_suffix: str | None = None) -> dict[str, str]:
    out = {}
    for item in plan.mutations:
        key = item.destination.as_posix()
        if destination_suffix:
            key = Path(item.destination).name
        out[item.artifact] = item.operation
    return out


class RuntimeInstallTests(unittest.TestCase):
    def test_plan_mode_has_zero_mutation(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            dist = _dist(root)
            home = root / "codex-home"
            home.mkdir()
            _write(home / "config.toml", 'model = "keep"\n', 0o600)
            before = tree_digests(home)
            plan = plan_live_install(
                "codex",
                home=home,
                dist=dist,
                engine_root=root / "engine",
                backup_root=root / "backups",
            )
            self.assertFalse(plan.blocked)
            self.assertEqual(tree_digests(home), before)
            self.assertFalse((root / "engine").exists())
            self.assertFalse((root / "backups").exists())

    def test_codex_existing_config_preserved_and_nexus_keys_created(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            dist = _dist(root)
            home = root / "codex-home"
            original = 'model = "keep"\nnotify = ["off"]\n'
            _write(home / "config.toml", original, 0o600)
            _write(home / "AGENTS.md", "# user instructions\nkeep me\n", 0o600)
            plan = plan_live_install(
                "codex",
                home=home,
                dist=dist,
                engine_root=root / "engine",
                backup_root=root / "backups",
            )
            result = apply_live_install(plan)
            self.assertTrue(result.ok)
            cfg = (home / "config.toml").read_text(encoding="utf-8")
            self.assertIn('model = "keep"', cfg)
            self.assertIn('notify = ["off"]', cfg)
            parsed = tomllib.loads(cfg)
            self.assertEqual(parsed["model"], "keep")
            self.assertEqual(parsed["sandbox_mode"], "workspace-write")
            self.assertEqual(parsed["approval_policy"], "on-request")
            self.assertEqual(stat.S_IMODE((home / "config.toml").stat().st_mode), 0o600)
            agents = (home / "AGENTS.md").read_text(encoding="utf-8")
            self.assertIn("# user instructions", agents)
            self.assertIn("keep me", agents)
            self.assertIn("NEXUS_HARNESS_BEGIN", agents)
            self.assertIn("NEXUS WORKFLOW IS MANDATORY", agents)

