    def test_rollback_restores_exact_bytes_and_modes(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            dist = _dist(root)
            home = root / "codex-home"
            _write(home / "config.toml", 'model = "keep"\n', 0o600)
